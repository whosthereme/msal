BLOCKS = (r"\emph{linear readout}", r"\emph{nonlinear readout; description absent or after the nonlinearity}",
  r"\emph{nonlinear readout; description before the nonlinearity}")


def num(v):
  return ("{+}%.1f" if v >= 0 else "-%.1f") % abs(v)


def cell(x):
  if x is None:
    return "---"
  return "$%s$ \\ci{%s}{%s}" % (num(x["pct"]), num(x["lo"]), num(x["hi"]))


def old_flow(label, nth):
  hits = [x for x in OLD.splitlines() if x.startswith("\\quad " + label + " &")]
  line = hits[nth]
  c = [x.strip() for x in line.rstrip("\\").split("&")]
  out = [c[2]]
  for x in c[3:5]:
    m = re.match(r"\$([^$]+)\$ \[\$([^$]+)\$\{,\} \$([^$]+)\$\]", x)
    out.append("---" if m is None else "$%s$ \\ci{%s}{%s}" % m.groups())
  return out


