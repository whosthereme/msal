import argparse
import json
from pathlib import Path

import numpy as np

KINDS = ("none", "additive", "film", "sal", "sal_noreg")
SEEDS = (1000, 1001)
SUITES = ("libero_spatial", "libero_object", "libero_goal", "libero_10")
COMPARISONS = (("additive", "none"), ("film", "none"), ("sal", "none"), ("film", "sal"))
EXPLORATORY = (("sal_noreg", "none"), ("sal_noreg", "sal"), ("film", "sal_noreg"))
N_BOOT = 10_000
BOOT_SEED = 20261022
LABEL = {"none": "None", "additive": "Additive", "film": "FiLM", "sal": "SAL", "sal_noreg": "SAL, no penalties"}
SUITE_LABEL = {"libero_spatial": "Spatial", "libero_object": "Object", "libero_goal": "Goal", "libero_10": "Long"}


def load(path: Path) -> np.ndarray:
    info = json.loads(path.read_text())
    rows = {(t["task_group"], t["task_id"]): t["metrics"]["successes"] for t in info["per_task"]}
    keys = sorted(rows, key=lambda k: (SUITES.index(k[0]), k[1]))
    if len(keys) != 40 or any(len(rows[k]) != 20 for k in keys):
        raise ValueError(f"{path}: expected 40 tasks x 20 episodes")
    return np.array([rows[k] for k in keys], dtype=float)


def summary(s: np.ndarray) -> dict:
    return {"overall": 100 * s.mean(),
            **{suite: 100 * s[10 * i:10 * (i + 1)].mean() for i, suite in enumerate(SUITES)}}


def compare(models: dict, a: str, b: str, exploratory: bool = False) -> dict | None:
    seeds = [s for s in SEEDS if (a, s) in models and (b, s) in models]
    rng = np.random.default_rng([BOOT_SEED, KINDS.index(a), KINDS.index(b)])
    if not seeds:
        return None
    per_seed = {}
    for s in seeds:
        x, y = models[(a, s)], models[(b, s)]
        per_seed[s] = {"diff_pp": 100 * (x.mean() - y.mean()),
                       "only_a": int(((x == 1) & (y == 0)).sum()), "only_b": int(((x == 0) & (y == 1)).sum())}
    d_task = np.mean([models[(a, s)].mean(1) - models[(b, s)].mean(1) for s in seeds], axis=0)
    idx = rng.integers(0, len(d_task), size=(N_BOOT, len(d_task)))
    boot = 100 * d_task[idx].mean(1)
    lo, hi = np.percentile(boot, [2.5, 97.5])
    reading = "better" if lo > 0 else "worse" if hi < 0 else "not distinguishable"
    return {"a": a, "b": b, "exploratory": exploratory, "seeds": seeds, "per_seed": per_seed,
            "mean_diff_pp": float(np.mean([v["diff_pp"] for v in per_seed.values()])),
            "boot95_pp": [float(lo), float(hi)], "reading": reading,
            "tasks_a_better": int((d_task > 0).sum()), "tasks_b_better": int((d_task < 0).sum())}


REGISTERED = [(k, s) for k in KINDS[:4] for s in SEEDS]
TABLES = Path(__file__).resolve().parents[1] / "manuscript" / "tables"
SHORT = {**LABEL, "sal_noreg": r"SAL, no pen.$^\dagger$"}
EOL = r" \\"


def _pp(x: float) -> str:
    return f"${x:+.1f}$".replace("+", "{+}") if x >= 0 else f"${x:.1f}$"


def main_table(models: dict, comps: list) -> str:
    complete = all(m in models for m in REGISTERED)
    vs_none = {c["a"]: c for c in comps if c["b"] == "none"}
    rows = []
    for kind in KINDS:
        seeds = [s for s in SEEDS if (kind, s) in models]
        if not seeds:
            rows.append(SHORT[kind] + r" & 0 & \multicolumn{6}{c}{\prelim{pending}}" + EOL)
            continue
        m = summary(np.concatenate([models[(kind, s)] for s in seeds], 1))
        cells = " & ".join(f"{m[suite]:.1f}" for suite in SUITES)
        if kind == "none":
            delta = "---"
        elif kind in vs_none:
            c = vs_none[kind]
            delta = f"{_pp(c['mean_diff_pp'])} [{_pp(c['boot95_pp'][0])}, {_pp(c['boot95_pp'][1])}]"
        else:
            delta = r"\prelim{pending}"
        rows.append(f"{SHORT[kind]} & {len(seeds)} & {cells} & {m['overall']:.1f} & {delta}" + EOL)
    n_done = sum(m in models for m in REGISTERED)
    note = "" if complete else rf" \prelim{{Partial: {n_done} of 8 registered models evaluated.}}"
    return "\n".join([
        "% generated by analysis/closed_loop.py; do not edit by hand",
        r"\begin{table}[t]",
        r"\caption{Closed-loop success (\%) of SmolVLA fine-tuned on LIBERO with the task code in each form: mean "
        r"over seeds, 800 episodes per seed. $\Delta$: difference from no code in percentage points with 95\% "
        r"task-bootstrap interval. $^\dagger$Exploratory arm, one seed." + note + "}",
        r"\label{tab:closed}",
        r"\centering\footnotesize\setlength{\tabcolsep}{2.0pt}",
        r"\begin{tabular}{@{}lcrrrrrl@{}}",
        r"\toprule",
        r"Code form & Seeds & Spatial & Object & Goal & Long & All & $\Delta$ [95\% CI]" + EOL,
        r"\midrule",
        *rows,
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table}",
        ""])


def supp_table(models: dict) -> str:
    rows = []
    for kind in KINDS:
        for s in SEEDS:
            if (kind, s) not in models:
                continue
            m = summary(models[(kind, s)])
            cells = " & ".join(f"{m[suite]:.1f}" for suite in SUITES)
            if kind != "none" and ("none", s) in models:
                x, y = models[(kind, s)], models[("none", s)]
                paired = f"{int(((x == 1) & (y == 0)).sum())}/{int(((x == 0) & (y == 1)).sum())}"
            else:
                paired = "---"
            rows.append(f"{SHORT[kind]} & {s} & {cells} & {m['overall']:.1f} & {paired}" + EOL)
    return "\n".join([
        "% generated by analysis/closed_loop.py; do not edit by hand",
        r"\begin{table}[h]",
        r"\caption{Closed-loop success (\%) of every model (200 episodes per suite). Paired: episodes won only by "
        r"the model / only by the no-code model of the same seed, on identical initial states. $^\dagger$Exploratory.}",
        r"\label{tab:s-closed}",
        r"\centering\footnotesize\setlength{\tabcolsep}{2.6pt}",
        r"\begin{tabular}{@{}lcrrrrrc@{}}",
        r"\toprule",
        r"Code form & Seed & Spatial & Object & Goal & Long & All & Paired" + EOL,
        r"\midrule",
        *rows,
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table}",
        ""])


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("root", type=Path)
    ap.add_argument("--out", type=Path, default=Path(__file__).with_name("closed_loop.json"))
    ap.add_argument("--tables", type=Path, default=TABLES)
    args = ap.parse_args()

    models = {}
    for kind in KINDS:
        for s in SEEDS:
            p = args.root / f"eval_{kind}_{s}" / "eval_info.json"
            if p.exists():
                models[(kind, s)] = load(p)

    result = {
        "models": {f"{k}-{s}": summary(v) for (k, s), v in models.items()},
        "means": {k: summary(np.concatenate([models[(k, s)] for s in SEEDS if (k, s) in models], 1))
                  for k in KINDS if any((k, s) in models for s in SEEDS)},
        "comparisons": [c for a, b in COMPARISONS if (c := compare(models, a, b)) is not None]
                       + [c for a, b in EXPLORATORY if (c := compare(models, a, b, True)) is not None],
        "protocol": {"n_boot": N_BOOT, "boot_seed": BOOT_SEED, "unit": "task (40), seeds pooled",
                     "stream": "per comparison: default_rng([boot_seed, KINDS.index(a), KINDS.index(b)])"},
    }
    args.out.write_text(json.dumps(result, indent=1))
    args.tables.mkdir(parents=True, exist_ok=True)
    (args.tables / "closed_loop_main.tex").write_text(main_table(models, result["comparisons"]))
    (args.tables / "closed_loop_supp.tex").write_text(supp_table(models))

    for name, m in result["models"].items():
        print(f"{name:14s} overall {m['overall']:5.1f}  " +
              "  ".join(f"{SUITE_LABEL[s]} {m[s]:5.1f}" for s in SUITES))
    for c in result["comparisons"]:
        seeds = "; ".join(f"seed {s}: {v['diff_pp']:+.1f} pp ({v['only_a']}/{v['only_b']})"
                          for s, v in c["per_seed"].items())
        lo, hi = c["boot95_pp"]
        print(f"{'[exploratory] ' if c['exploratory'] else ''}{c['a']} vs {c['b']}: mean {c['mean_diff_pp']:+.1f} pp [{lo:+.1f}, {hi:+.1f}] "
              f"-> {c['reading']} | {seeds}")


if __name__ == "__main__":
    main()
