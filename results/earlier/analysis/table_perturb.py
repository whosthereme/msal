import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
d = json.loads((ROOT / "analysis" / "cl_perturb.json").read_text())
S, C = d["success"], d["contrasts"]
ROWS = [("ret_replay_k1", r"Replay$^\dagger$, $k{=}1$"), ("ret_replay_k16", r"Replay$^\dagger$, $k{=}16$"),
        ("msal_k1", r"\Method{}, $k{=}1$"), ("msal_k16", r"\Method{}, $k{=}16$"),
        ("bf_k16", r"Fitted code$^\dagger$, $k{=}16$"), ("ft_k16", r"Fine-tune, $k{=}16$"),
        ("seen", "Trained on task")]


def pp(v):
    return f"${'{+}' if v >= 0 else '-'}{abs(v):.1f}$"


def ci(c):
    return f"{pp(c['estimate_pp'])} [{pp(c['ci95_pp'][0])}, {pp(c['ci95_pp'][1])}]"


lines = ["% generated by analysis/table_perturb.py; do not edit by hand", r"\begin{table}[h]",
         r"\caption{Closed-loop success (\%, mean over the eight held tasks) with objects moved up to 4~cm (L1) or "
         r"8~cm (L2) from LIBERO's initial states; L0 unperturbed. Change: L2 minus L0 (points, 95\% two-level "
         r"bootstrap interval). $^\dagger$Exploratory policy.}",
         r"\label{tab:s-perturb}", r"\centering\footnotesize\setlength{\tabcolsep}{2.4pt}",
         r"\begin{tabular}{@{}lrrrl@{}}", r"\toprule", r"Policy & L0 & L1 & L2 & Change L0$\to$L2\\", r"\midrule"]
for key, label in ROWS:
    lines.append(f"{label} & {S[key + '@L0']['mean_over_tasks']:.1f} & {S[key + '@L1']['mean_over_tasks']:.1f} & "
                 f"{S[key + '@L2']['mean_over_tasks']:.1f} & {ci(C[f'S6 {key} L2-L0'])}\\\\")
lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
out = ROOT / "manuscript" / "tables_v2" / "perturb_supp.tex"
out.write_text("\n".join(lines), encoding="utf-8")
print("written", out)
for k in ("P1 DiD k16 L2: (replay16-msal16)@L2 - @L0", "P2 DiD k1 L2: (replay1-msal1)@L2 - @L0", "S1 DiD k16 L1",
          "S2 DiD k1 L1", "S3 replay16-msal16 @L2", "S4 replay1-msal1 @L2", "S5a bf16-replay16 @L2"):
    print(k, ci(C[k]))
