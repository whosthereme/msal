import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NAMES = {"zero": "zero-shot", "msal_k1": r"\Method{} $k{=}1$", "msal_k16": r"\Method{} $k{=}16$",
         "ft_k1": r"FT $k{=}1$", "ft_k16": r"FT $k{=}16$", "seen": "seen-task head",
         "roft_k1": r"RO $k{=}1$", "roft_k16": r"RO $k{=}16$"}


def pp(v):
    return f"${'{+}' if v >= 0 else '-'}{abs(v):.1f}$"


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--json", type=Path, default=ROOT / "analysis" / "cl_adapt.json")
    args = ap.parse_args()
    b = json.loads(args.json.read_text())["stage_b"]
    succ = b["success_pct"]
    rows = []
    for name, c in b["comparisons"].items():
        if "a" not in c:
            continue
        rows.append(f"{name} & {NAMES[c['a']]} vs {NAMES[c['b']]} & {succ[c['a']]['overall']:.1f} / "
                    f"{succ[c['b']]['overall']:.1f} & {pp(c['diff_pp'])} [{pp(c['boot95_pp'][0])}, "
                    f"{pp(c['boot95_pp'][1])}] & {c['tasks_a_better']}/{c['tasks_b_better']}\\\\")
        if name == "C2":
            rows.append(r"\midrule")
    ro_path = ROOT / "analysis" / "cl_readout.json"
    if ro_path.exists():
        ro = json.loads(ro_path.read_text())
        s = {p: v["mean_over_tasks"] for p, v in ro["success_pct"].items()}
        rows.append(r"\midrule")
        for name, c in ro["comparisons"].items():
            rows.append(f"{name} & {NAMES[c['a']]} vs {NAMES[c['b']]} & {s[c['a']]:.1f} / {s[c['b']]:.1f} & "
                        f"{pp(c['diff_pp'])} [{pp(c['boot95_pp'][0])}, {pp(c['boot95_pp'][1])}] & "
                        f"{c['tasks_a_better']}/{c['tasks_b_better']}\\\\")
    lines = [
        "% generated by analysis/table_cl_adapt.py; do not edit by hand",
        r"\begin{table}[h]",
        r"\caption{Registered comparisons of the closed-loop adaptation study: success (\%) of the two policies "
        r"over the eight held tasks (50 paired episodes each), difference in percentage points with 95\% two-level "
        r"bootstrap interval (tasks, then episodes), and tasks on which each policy was better. C1 and C2 are "
        r"primary. FT: fine-tuning the whole head. R1--R6: follow-up registered later, RO: fine-tuning the readout "
        r"alone (R1 and R2 primary).}",
        r"\label{tab:s-cl-adapt}",
        r"\centering\footnotesize\setlength{\tabcolsep}{2.0pt}",
        r"\begin{tabular}{@{}llccc@{}}",
        r"\toprule",
        r" & Comparison & Success & $\Delta$ [95\% CI] & Tasks\\",
        r"\midrule",
        *rows,
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table}",
        "",
    ]
    out = ROOT / "manuscript" / "tables_v2" / "cl_adapt_supp.tex"
    out.write_text("\n".join(lines), encoding="utf-8")
    print("written", out)


if __name__ == "__main__":
    main()
