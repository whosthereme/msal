import json
import math
from pathlib import Path

import numpy as np
from scipy import stats

ROOT = Path(__file__).resolve().parent.parent
A = ROOT / "analysis"
OUT = ROOT / "manuscript" / "tables_v2" / "adapt_supp.tex"
KS = (1, 2, 4, 8, 16)


def per_seed(comp):
    s = comp["selection"] if "selection" in comp else comp
    return np.array([v["mean_log_ratio"] for _, v in sorted(s["per_seed"].items())])


def summary(x):
    m, se = x.mean(), x.std(ddof=1) / math.sqrt(len(x))
    t = stats.t.ppf(0.975, len(x) - 1)
    return [100 * (math.exp(v) - 1) for v in (m, m - t * se, m + t * se)]


def fmt(p):
    m, lo, hi = p
    sgn = lambda v: f"${'-' if v < 0 else '{+}'}{abs(v):.1f}$"
    return f"{sgn(m)} [{sgn(lo)}{{,}} {sgn(hi)}]"


hyb = json.loads((A / "hyb_final.json").read_text())["comparisons"]
combo = json.loads((A / "combo_final.json").read_text())["comparisons"]
l40 = json.loads((A / "l40_final.json").read_text())["comparisons"]

dev = {"lib": {k: per_seed(hyb[f"curve: hybrid k={k} vs zero-shot"]) for k in KS},
       "inv": {k: per_seed(hyb[f"curve: inversion k={k} vs zero-shot"]) for k in KS},
       "all": {k: per_seed(combo[f"curve: combination k={k} vs zero-shot"]) for k in KS}}
lib40 = {"lib": {k: per_seed(l40[f"curve: hybrid k={k} vs zero-shot"]) for k in KS},
         "inv": {k: per_seed(l40[f"curve: inversion k={k} vs zero-shot"]) for k in KS},
         "all": {k: per_seed(l40[f"curve: combination k={k} vs zero-shot"]) for k in KS}}

for k in KS:
    reg = per_seed(combo[f"curve: combination k={k} vs inversion"])
    assert np.allclose(dev["all"][k] - dev["inv"][k], reg, atol=1e-9), ("dev", k)
for k, name in ((1, "L4 combination k=1 vs inversion k=1"), (4, "L2 combination k=4 vs inversion k=4"),
                (16, "L1 combination k=16 vs inversion k=16")):
    assert np.allclose(lib40["all"][k] - lib40["inv"][k], per_seed(l40[name]), atol=1e-9), ("l40", k)

rows = []
for title, d in ((r"Development (41 spatial tasks, 205 folds)", dev), (r"LIBERO40 (40 tasks, 200 folds)", lib40)):
    rows.append(r"\multicolumn{5}{@{}l}{\emph{" + title + r"}}\\")
    for k in KS:
        cells = [fmt(summary(d["lib"][k])), fmt(summary(d["inv"][k])), fmt(summary(d["all"][k])),
                 fmt(summary(d["all"][k] - d["inv"][k]))]
        rows.append(rf"\quad {k} & " + " & ".join(cells) + r"\\")

tex = r"""% generated by analysis/table_adapt_v2.py; do not edit by hand
\begin{table*}[t]
\caption{Few-shot adaptation at every $k$: change in held-task flow MSE (\%, 95\% $t$ interval over five seeds).}
\label{tab:s-adapt}
\centering\footnotesize\setlength{\tabcolsep}{6pt}
\begin{tabular}{@{}lllll@{}}
\toprule
$k$ & Library vs zero-shot & Inversion vs zero-shot & \Method{} vs zero-shot & \Method{} vs inversion\\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}
\end{table*}
"""
OUT.write_text(tex, encoding="utf-8")
print("written", OUT)
print("\n".join(rows))
