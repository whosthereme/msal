import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "manuscript" / "tables_v2"
SHOTS = ("1", "2", "4", "8", "16")


def sgn(v):
    return f"${'-' if v < 0 else '{+}'}{abs(v):.1f}$"


def cell(c):
    if not c or "pct_ci95" not in c:
        return "---"
    lo, hi = c["pct_ci95"]
    return f"{sgn(c['pct'])} [{sgn(lo)}{{,}} {sgn(hi)}]"


def load(directory, stem):
    for name in (f"{stem}_final.json", f"{stem}_interim.json"):
        p = directory / name
        if p.exists():
            return json.loads(p.read_text()), name.endswith("interim.json")
    return None, False


def pending(label, caption):
    return (f"% generated by analysis/table_newstudies_v2.py; do not edit by hand\n\\begin{{table}}[h]\n"
            f"\\caption{{{caption} \\prelim{{Pending: the study has not run yet.}}}}\n\\label{{{label}}}\n"
            "\\centering\\footnotesize\\begin{tabular}{@{}l@{}}\\toprule pending\\\\\\bottomrule\\end{tabular}\n\\end{table}\n")


def cov_table(res, interim):
    cap = ("Source coverage (development): change in held-task flow MSE (\\%, 95\\% $t$ interval) with $n$ source "
           "tasks.")
    if res is None:
        return pending("tab:s-cov", cap)
    if interim:
        cap += " \\prelim{Interim: not all folds complete.}"
    comps = res["comparisons"]
    names = [("V1 MSAL vs inversion, k=16", "\\Method{} vs inv., $k{=}16$"),
             ("V2 MSAL vs inversion, k=1", "\\Method{} vs inv., $k{=}1$"),
             ("V3 library only vs zero-shot, k=16", "Library vs zero-shot, $k{=}16$"),
             ("V4 MSAL vs zero-shot, k=16", "\\Method{} vs zero-shot, $k{=}16$")]
    levels = sorted({n for name, _ in names for n in comps.get(name, {})}, key=int)
    rows = []
    for n in levels:
        v1 = comps.get(names[0][0], {}).get(n, {})
        won = f"{v1['folds_won']}/{v1['folds']}" if v1 else "---"
        rows.append(f"{n} & " + " & ".join(cell(comps.get(key, {}).get(n)) for key, _ in names) + f" & {won}\\\\")
    trend = res.get("trend_V1_slope_per_doubling")
    note = ""
    if trend and "ci95" in trend:
        note = (f" Per doubling of $n$, the log ratio of \\Method{{}} to inversion at $k{{=}}16$ changes by "
                f"${trend['mean']:+.3f}$ (interval ${trend['ci95'][0]:+.3f}$ to ${trend['ci95'][1]:+.3f}$).")
    return ("% generated by analysis/table_newstudies_v2.py; do not edit by hand\n\\begin{table*}[t]\n"
            f"\\caption{{{cap}}}\n\\label{{tab:s-cov}}\n\\centering\\footnotesize\\setlength{{\\tabcolsep}}{{5pt}}\n"
            "\\begin{tabular}{@{}rlllll@{}}\n\\toprule\n$n$ & " + " & ".join(h for _, h in names)
            + " & Folds won (V1)\\\\\n\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n\\end{table*}\n")


def setting(key):
    k, variant, lr, steps = key.split("_")
    rate = {"0.0001": "$10^{-4}$", "0.001": "$10^{-3}$"}.get(lr[2:], lr[2:])
    return f"{'readout' if variant == 'readout' else 'whole head'}, {rate}, {steps[1:]} steps"


def ft_table(res, interim):
    cap = ("Fine-tuning (FT) baseline: change in held-task flow MSE (\\%, 95\\% $t$ interval); negative "
           "``\\Method{} vs FT'' favours \\Method{}. $^\\dagger$Exploratory.")
    if res is None:
        return pending("tab:s-ft", cap)
    if interim:
        cap += " \\prelim{Interim: not all folds complete.}"
    rows = []
    for family, title in (("dev", "Development (205 folds)"), ("l40", "LIBERO40 (200 folds)")):
        rows.append(f"\\multicolumn{{6}}{{@{{}}l}}{{\\emph{{{title}}}}}\\\\")
        for k in SHOTS:
            sel = res.get("selected", {}).get(k)
            c = res.get("comparisons", {}).get(family, {}).get(k, {})
            secs = res.get("cost_seconds", {}).get(family, {}).get(k, {}).get("selected_setting_median")
            best = cell(c.get("exploratory: MSAL vs LIBERO40-best fine-tuning")) if family == "l40" else "---"
            rows.append(f"\\quad {k} & {setting(sel) if sel else '---'} & {cell(c.get('selected fine-tuning vs zero-shot'))} & "
                        f"{cell(c.get('MSAL vs selected fine-tuning'))} & {best} & "
                        + (f"{secs:.1f}\\\\" if secs is not None else "---\\\\"))
    return ("% generated by analysis/table_newstudies_v2.py; do not edit by hand\n\\begin{table*}[t]\n"
            f"\\caption{{{cap}}}\n\\label{{tab:s-ft}}\n\\centering\\footnotesize\\setlength{{\\tabcolsep}}{{4pt}}\n"
            "\\begin{tabular}{@{}llllll@{}}\n\\toprule\n$k$ & Selected setting & FT vs zero-shot & \\Method{} vs FT & "
            "\\Method{} vs best FT$^\\dagger$ & FT time (s)\\\\\n\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n\\end{table*}\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results-dir", type=Path, default=ROOT / "analysis")
    parser.add_argument("--out-dir", type=Path, default=OUT)
    args = parser.parse_args()
    args.out_dir.mkdir(parents=True, exist_ok=True)
    cov, cov_interim = load(args.results_dir, "cov")
    ft, ft_interim = load(args.results_dir, "ft")
    (args.out_dir / "cov_supp.tex").write_text(cov_table(cov, cov_interim), encoding="utf-8")
    (args.out_dir / "ft_supp.tex").write_text(ft_table(ft, ft_interim), encoding="utf-8")
    print("written", args.out_dir / "cov_supp.tex", "(pending)" if cov is None else "(interim)" if cov_interim else "")
    print("written", args.out_dir / "ft_supp.tex", "(pending)" if ft is None else "(interim)" if ft_interim else "")


if __name__ == "__main__":
    main()
