import json
import math
import statistics as st
from pathlib import Path

from aggregate_n1n2 import seed_summary

ROOT = Path(__file__).resolve().parents[1]
HEADS = [
    ("plain", "No task input", "linear readout", False),
    ("ctx_add", "Additive", "linear readout", False),
    ("film", "FiLM", "linear readout", False),
    ("bilinear", "Bilinear", "linear readout", False),
    ("sal", "SAL", "linear readout", False),
    ("plain_nl", "No task input", "nonlinear readout", False),
    ("moe_desc", "Softmax mixture of experts", "nonlinear readout", False),
    ("sal_nl", "SAL, nonlinear atoms", "nonlinear readout", False),
    ("sal_nlb", r"SAL, nonlinear base and atoms$^\dagger$", "nonlinear readout", True),
    ("film_nl", r"FiLM + MLP (\Method{} head)", "nonlinear readout", False),
]


def load():
    by = {}
    for p in (ROOT / "results_remote" / "n1n2").glob("*/folds.jsonl"):
        if "anchor" in p.parent.name or p.parent.name.startswith("lang"):
            continue
        for x in p.read_text().splitlines():
            if x.strip():
                r = json.loads(x)
                if r["feature"] == "blind":
                    by.setdefault(r["arm"], {})[(r["seed"], int(r["held_task"]))] = r
    return by


def paired(by, a, b):
    per = []
    for s in sorted({k[0] for k in by[a]}):
        keys = [k for k in by[a] if k[0] == s and k in by[b]]
        per.append(st.mean(math.log(by[a][k]["main_selection"] / by[b][k]["main_selection"]) for k in keys))
    return seed_summary(per)


def fmt(summary):
    lo, hi = summary["pct_ci95"]
    sign = lambda x: f"${x:+.1f}$".replace("+", "{+}") if x >= 0 else f"${x:.1f}$"
    return f"{sign(summary['pct'])} [{sign(lo)}, {sign(hi)}]"


def main():
    by = load()
    rows, last_group = [], None
    for arm, label, group, _ in HEADS:
        records = list(by[arm].values())
        if len(records) != 205:
            raise RuntimeError(f"{arm}: {len(records)} folds, expected 205")
        params = records[0]["task_conditioned_parameters"]
        mse = st.mean(r["main_selection"] for r in records)
        vs_film = "---" if arm == "film" else fmt(paired(by, arm, "film"))
        vs_mod = "---" if arm == "film_nl" else fmt(paired(by, arm, "film_nl"))
        if group != last_group:
            rows.append(rf"\multicolumn{{5}}{{@{{}}l}}{{\emph{{{group}}}}}\\")
            last_group = group
        rows.append(rf"\quad {label} & {params:,} & {mse:.3f} & {vs_film} & {vs_mod}\\".replace(",", "{,}"))
        print(f"{arm:10s} params {params:>9,} mse {mse:.4f}  vs FiLM {vs_film:28s} vs FiLM+MLP {vs_mod}")
    table = "\n".join([
        "% generated by analysis/table_heads_v2.py; do not edit by hand",
        r"\begin{table*}[t]",
        r"\caption{Zero-shot heads on the same 205 leave-one-task-out folds (41 spatial tasks, five seeds): task-"
        r"conditioned parameters, mean held-task flow MSE, and paired change against FiLM with a linear readout and "
        r"against \Method{}'s modulated nonlinear head (mean over seeds, 95\% $t$ interval). Nonlinear readouts are "
        r"capacity-matched (1{,}472 SiLU units). \SAL{}: shared atom library (linear atoms unless noted). "
        r"$^\dagger$Exploratory, specified after an interim look.}",
        r"\label{tab:heads}",
        r"\centering\footnotesize\setlength{\tabcolsep}{4pt}",
        r"\begin{tabular}{@{}lrrll@{}}",
        r"\toprule",
        r"Head & Params & MSE & vs FiLM (\%) & vs FiLM + MLP (\%)\\",
        r"\midrule",
        *rows,
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table*}",
        ""])
    out = ROOT / "manuscript" / "tables_v2" / "heads.tex"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(table)
    print("written", out)


if __name__ == "__main__":
    main()
