import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
A = ROOT / "analysis"


def pct(d, name, split="selection"):
    c = d["comparisons"][name]
    c = c.get(split, c)
    return c["across_seeds"]["pct"] if "across_seeds" in c else c["pct"]


def cpu():
    out = {}
    for line in (ROOT / "results_remote" / "bench_cpu" / "bench.jsonl").read_text().splitlines():
        r = json.loads(line)
        if r["threads"] == 4:
            out[(r["method"], r["k"])] = r["median_seconds"]
    return out


def t(sec):
    if sec is None:
        return "---"
    return f"{sec:.2f}~s" if sec < 1 else f"{sec:.1f}~s" if sec < 60 else f"{sec / 60:.0f}~min"


def f(x):
    return f"${x:+.0f}$".replace("+", "{+}") if x is not None else "---"


def main():
    hyb, combo = json.loads((A / "hyb_final.json").read_text()), json.loads((A / "combo_final.json").read_text())
    l40, ft = json.loads((A / "l40_final.json").read_text()), json.loads((A / "ft_final.json").read_text())
    c = cpu()
    prep = json.loads((ROOT / "results_remote" / "bench_cpu" / "prep.json").read_text())
    sel = ft["selected"]
    steps = {k: int(sel[k].split("_s")[-1]) for k in ("1", "16")}
    best = {k: min(ft["settings_vs_zero_shot"]["l40"][k].items(), key=lambda kv: kv[1]["mean"]) for k in ("1", "16")}
    best_steps = {k: int(best[k][0].split("_s")[-1]) for k in best}
    ft_time = lambda n: c.get((f"ft_all_{n}", 16))
    ro = json.loads((A / "ft_readout.json").read_text())
    ro_steps = {k: int(ro["selected_readout"][k].split("_s")[-1]) for k in ("1", "16")}
    ro_pct = lambda fam, k: ro["comparisons"][fam][k]["readout fine-tuning vs zero-shot"]["pct"]
    rows = [
        ("Code only", "no", "16", c.get(("code_only", 1)), c.get(("code_only", 16)),
         pct(hyb, "curve: hybrid k=1 vs zero-shot"), pct(hyb, "curve: hybrid k=16 vs zero-shot"),
         pct(l40, "curve: hybrid k=1 vs zero-shot"), pct(l40, "curve: hybrid k=16 vs zero-shot")),
        (r"\Method{}", "no", "37 / 81", c.get(("msal", 1)), c.get(("msal", 16)),
         pct(combo, "curve: combination k=1 vs zero-shot"), pct(combo, "curve: combination k=16 vs zero-shot"),
         pct(l40, "curve: combination k=1 vs zero-shot"), pct(l40, "curve: combination k=16 vs zero-shot")),
        ("FT head, dev.", "all", "18\\,M", ft_time(steps["1"]), ft_time(steps["16"]),
         ft["comparisons"]["dev"]["1"]["selected fine-tuning vs zero-shot"]["pct"],
         ft["comparisons"]["dev"]["16"]["selected fine-tuning vs zero-shot"]["pct"],
         ft["comparisons"]["l40"]["1"]["selected fine-tuning vs zero-shot"]["pct"],
         ft["comparisons"]["l40"]["16"]["selected fine-tuning vs zero-shot"]["pct"]),
        ("FT head, LIBERO$^\\dagger$", "all", "18\\,M", ft_time(best_steps["1"]), ft_time(best_steps["16"]),
         None, None, best["1"][1]["pct"], best["16"][1]["pct"]),
        ("FT readout, dev.$^\\dagger$", "readout", "1\\,M", c.get((f"ft_readout_{ro_steps['1']}", 16)),
         c.get((f"ft_readout_{ro_steps['16']}", 16)), ro_pct("dev", "1"), ro_pct("dev", "16"),
         ro_pct("l40", "1"), ro_pct("l40", "16")),
    ]
    body = "\n".join(f"{name} & {s} & {t(a)} & {t(b)} & {f(d1)} & {f(d16)} & {f(l1)} & {f(l16)}\\\\"
                     for name, w, s, a, b, d1, d16, l1, l16 in rows)
    tex = rf"""% generated by analysis/table_deploy_v2.py; do not edit by hand
\begin{{table}}[t]
\caption{{Adapting to a new task at deployment. Code only: the closed-form residual code; FT: fine-tuning the
whole head or its readout alone, at the setting chosen on the development (dev.) or the LIBERO tasks;
$^\dagger$not a registered comparison. Stored: numbers kept per task (dev.\ / LIBERO); only fine-tuning changes
weights. CPU: four threads of an i9-14900K. Error: change in held-task flow MSE against the zero-shot head (\%,
five seeds).}}
\label{{tab:deploy}}
\centering\footnotesize\setlength{{\tabcolsep}}{{2.2pt}}
\begin{{tabular}}{{@{{}}lc rr rr rr@{{}}}}
\toprule
& & \multicolumn{{2}}{{c}}{{CPU time}} & \multicolumn{{2}}{{c}}{{Dev.\ error}} & \multicolumn{{2}}{{c}}{{LIBERO error}}\\
\cmidrule(lr){{3-4}}\cmidrule(lr){{5-6}}\cmidrule(l){{7-8}}
Method & Stored & $k{{=}}1$ & $16$ & $1$ & $16$ & $1$ & $16$\\
\midrule
{body}
\bottomrule
\end{{tabular}}
\end{{table}}
"""
    out = ROOT / "manuscript" / "tables_v2" / "deploy.tex"
    out.write_text(tex, encoding="utf-8")
    print(tex)
    assert prep["head_parameters"] == 17_939_872 and prep["readout_parameters"] == 977_568


if __name__ == "__main__":
    main()
